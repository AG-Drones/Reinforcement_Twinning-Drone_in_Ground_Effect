def get_rows_between(t_start=None, t_end=None):
    t0 = log_data[0]["t"]
    rows = []

    for d in log_data:
        t_rel = d["t"] - t0
        if t_start is not None and t_rel < t_start:
            continue
        if t_end is not None and t_rel > t_end:
            continue

        row = d.copy()
        row["t_rel"] = t_rel
        rows.append(row)

    return rows


def get_zoom_rows_by_x(x_start, x_end):
    """Return the first forward-flight samples from x_start through x_end.

    The limits are detected from the measured x position. The zoomed time is
    reset so that t=0 corresponds to the first sample at or beyond x_start.
    """
    if not log_data:
        return []

    start_index = None
    end_index = None

    for i, sample in enumerate(log_data):
        x_value = float(sample["x"])
        if start_index is None and x_value >= float(x_start):
            start_index = i
        if start_index is not None and x_value >= float(x_end):
            end_index = i
            break

    if start_index is None:
        raise RuntimeError(
            f"Zoomed window not found: measured x never reached {float(x_start):.3f} m."
        )
    if end_index is None:
        raise RuntimeError(
            f"Zoomed window not found: measured x never reached {float(x_end):.3f} m."
        )

    rows = []
    zoom_t0 = float(log_data[start_index]["t"])
    for sample in log_data[start_index:end_index + 1]:
        row = sample.copy()
        row["t_rel"] = float(sample["t"]) - zoom_t0
        rows.append(row)

    return rows


