def load_reference_governor_policy(path):
    path = Path(path)
    if not path.exists():
        raise FileNotFoundError(
            f"Reference-governor policy not found: {path}. "
            "Run the selected MB mission script first."
        )
    with np.load(path, allow_pickle=False) as data:
        required = {
            "x_policy", "delta_z_reference", "height_in_rotor_radii",
            "horizontal_velocity", "mission_type", "policy_source",
        }
        missing = required.difference(data.files)
        if missing:
            raise KeyError(f"Missing policy fields in {path}: {sorted(missing)}")
        policy = {
            "x_policy": np.asarray(data["x_policy"], dtype=float),
            "delta_z_reference": np.asarray(data["delta_z_reference"], dtype=float),
            "height_in_rotor_radii": float(data["height_in_rotor_radii"]),
            "horizontal_velocity": float(data["horizontal_velocity"]),
            "mission_type": str(data["mission_type"]),
            "policy_source": str(data["policy_source"]),
            "identification_iteration": str(data["identification_iteration"]),
            "experiment_iteration": (
                str(data["experiment_iteration"])
                if "experiment_iteration" in data.files
                else str(data["identification_iteration"])
            ),
            "trajectory_execution": str(data["trajectory_execution"]).lower(),
            "minimum_actual_rotor_clearance_m": (
                float(data["minimum_actual_rotor_clearance_m"])
                if "minimum_actual_rotor_clearance_m" in data.files
                else None
            ),
            "rt_selection_version": (
                str(data["rt_selection_version"])
                if "rt_selection_version" in data.files else None
            ),
            "rt_exact_mpc_in_candidate_set": (
                bool(data["rt_exact_mpc_in_candidate_set"])
                if "rt_exact_mpc_in_candidate_set" in data.files else False
            ),
            "rt_selected_is_exact_mpc": (
                bool(data["rt_selected_is_exact_mpc"])
                if "rt_selected_is_exact_mpc" in data.files else False
            ),
        }
    n = policy["x_policy"].size
    if policy["delta_z_reference"].shape != (n,):
        raise ValueError("delta_z_reference and x_policy must have equal one-dimensional shape")
    if n < 2 or np.any(np.diff(policy["x_policy"]) <= 0.0):
        raise ValueError("x_policy must be strictly increasing")
    if policy["mission_type"] != "GE_VERTICAL_REFERENCE_GOVERNOR":
        raise ValueError(f"Unsupported mission type: {policy['mission_type']}")
    if policy["trajectory_execution"] != "spatial":
        raise ValueError("Reference-governor experiments require the spatial mission")
    source = policy["policy_source"]
    if MISSION_PHASE == "rt" and not (
            source.startswith("RT_") or source == "expected_improvement_policy"):
        raise ValueError(
            "RT mode requires an expected-improvement policy generated by "
            f"design_next_experiment.py; found {source!r}."
        )
    if MISSION_PHASE == "performance" and (
            source.startswith("RT_") or source == "expected_improvement_policy"):
        raise ValueError(
            "Performance mode found an expected-improvement policy. Generate the "
            "model-based policy again or set MISSION_PHASE='rt'."
        )
    if (MISSION_PHASE == "expand_performance"
            and source != "MB_ExpandPerfomance_NextMission"):
        raise ValueError(
            "expand_performance mode requires a reward-population policy."
        )
    if (MISSION_PHASE == "rt_calibration"
            and source != "RT_Calibration"):
        raise ValueError(
            "rt_calibration mode requires transfer_calibration.py output."
        )
    if (MISSION_PHASE == "rt_general" and source != "RT_General"):
        raise ValueError(
            "rt_general mode requires generalized_policy.py output."
        )
    if (MISSION_PHASE == "rt_edge_validation"
            and source != "RT_LocalCalibration"):
        raise ValueError(
            "rt_edge_validation mode requires RT_LocalCalibration.py output."
        )
    if abs(policy["delta_z_reference"][0]) > 1.0e-6:
        raise ValueError("The first vertical-reference correction must be zero")
    if np.max(np.abs(policy["delta_z_reference"])) > 4.55 * ROTOR_RADIUS:
        raise ValueError("Reference correction exceeds the configured 1R--6R knot envelope")
    if policy["minimum_actual_rotor_clearance_m"] is None:
        raise KeyError(
            "Policy has no validated DT clearance. Regenerate it with the current "
            "selected MB mission script."
        )
    predicted_clearance = float(policy["minimum_actual_rotor_clearance_m"])
    if predicted_clearance < 0.50 * ROTOR_RADIUS - 1.0e-5:
        raise ValueError(
            "Policy violates the required DT clearance: "
            f"{predicted_clearance / ROTOR_RADIUS:.3f}R < 0.500R"
        )
    policy["minimum_actual_rotor_clearance_m"] = predicted_clearance
    return policy

