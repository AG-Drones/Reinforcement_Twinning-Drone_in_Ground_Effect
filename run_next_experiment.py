def voltage_to_percent(v):
    table = [
        (4.20, 100), (4.15, 90), (4.11, 80), (4.08, 70),
        (4.02, 60), (3.98, 50), (3.95, 40), (3.91, 30),
        (3.87, 20), (3.83, 10), (3.50, 0),
    ]

    if v >= 4.20:
        return 100.0
    if v <= 3.50:
        return 0.0

    for i in range(len(table) - 1):
        v_hi, p_hi = table[i]
        v_lo, p_lo = table[i + 1]
        if v_lo <= v <= v_hi:
            alpha = (v - v_lo) / (v_hi - v_lo)
            return p_lo + alpha * (p_hi - p_lo)

    return 0.0


