def _rows_tcmd(rows):
    collective_pwm = np.asarray(
        [row["thrust"] for row in rows],
        dtype=float,
    )
    return np.asarray(collective_command_to_thrust(collective_pwm), dtype=float)


def _rows_feedforward_thrust_normalized(rows, t_oge):
    """Convert the applied collective PWM offset to an equivalent thrust increment.

    The conversion uses the same PWM-to-thrust relation used for T_cmd.  The
    offset is applied to the per-motor OGE operating point, so zero PWM offset
    corresponds exactly to zero on the normalized thrust axis.
    """
    applied_offset = np.asarray(
        [row["ge_ff_applied"] for row in rows],
        dtype=float,
    )
    t_oge = np.asarray(t_oge, dtype=float)
    delta_thrust = (
        4.0
        * params.FIRMWARE_THRUST_MAX_PER_MOTOR
        * applied_offset
        / 65535.0
    )
    return delta_thrust / t_oge


