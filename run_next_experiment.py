def _smoothstep(value):
    u = float(np.clip(value, 0.0, 1.0))
    return u**3 * (10.0 - 15.0 * u + 6.0 * u**2)


def spatial_velocity_reference(x_position):
    velocity = float(HORIZONTAL_VELOCITY)
    minimum_speed = min(velocity, float(SPATIAL_MIN_FORWARD_SPEED))
    speed_range_squared = velocity**2 - minimum_speed**2
    if x_position < float(X_ACCEL_END):
        blend = _smoothstep(
            (x_position - float(X_START)) / float(X_ACCEL_END - X_START)
        )
        return float(np.sqrt(minimum_speed**2 + speed_range_squared * blend))
    if x_position < float(X_SPATIAL_DECEL_START):
        return velocity
    if x_position < float(X_SPATIAL_STOP):
        blend = _smoothstep(
            (x_position - float(X_SPATIAL_DECEL_START))
            / float(X_SPATIAL_STOP - X_SPATIAL_DECEL_START)
        )
        return float(np.sqrt(minimum_speed**2 + speed_range_squared * (1.0 - blend)))
    return 0.0


def execute_spatial_reference_governor(scf, policy):
    """Stream the nominal vx command and the governed z reference versus measured x."""
    low_level = scf.cf.commander
    if latest_position_sample is None:
        raise RuntimeError("Spatial RG mission cannot start: no position sample is available.")
    x_policy = policy["x_policy"]
    delta_z = policy["delta_z_reference"]
    command_period = 1.0 / float(SPATIAL_COMMAND_HZ)
    mission_timeout = 20.0 + 2.0 * (float(X_SPATIAL_STOP)-float(X_START))/float(HORIZONTAL_VELOCITY)
    mission_start_wall = time.monotonic()
    progress_x = max(float(X_START), float(latest_position_sample["x"]))
    next_command_wall = mission_start_wall
    set_ge_feedforward(scf, False, 0)

    while progress_x < float(X_SPATIAL_STOP):
        now = time.monotonic()
        sample = latest_position_sample
        if now - float(sample["wall_time"]) > float(SPATIAL_LOG_TIMEOUT):
            low_level.send_hover_setpoint(0.0, 0.0, 0.0, control_mission_height())
            raise RuntimeError("Spatial RG mission aborted: position log is stale.")
        progress_x = max(progress_x, float(sample["x"]))
        if now - mission_start_wall > mission_timeout:
            low_level.send_hover_setpoint(0.0, 0.0, 0.0, control_mission_height())
            raise RuntimeError("Spatial RG mission aborted: stop position was not reached before timeout.")
        dz = float(np.interp(progress_x, x_policy, delta_z, left=0.0, right=0.0))
        z_command = control_mission_height() + dz
        vy_command = float(np.clip(
            -float(SPATIAL_Y_KP) * (float(sample["y"]) - float(Y_TARGET)),
            -float(SPATIAL_MAX_LATERAL_SPEED), float(SPATIAL_MAX_LATERAL_SPEED),
        ))
        low_level.send_hover_setpoint(
            spatial_velocity_reference(progress_x), vy_command, 0.0, z_command
        )
        next_command_wall += command_period
        time.sleep(max(0.0, next_command_wall - time.monotonic()))

    hold_end = time.monotonic() + float(SPATIAL_FINAL_HOLD_TIME)
    while time.monotonic() < hold_end:
        low_level.send_hover_setpoint(0.0, 0.0, 0.0, control_mission_height())
        time.sleep(command_period)
    low_level.send_notify_setpoint_stop(100)

